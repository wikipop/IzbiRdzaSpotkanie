//! `cargo xtask gen-keys`: a fresh Ed25519 key pair in `backend/.env`.

use std::path::Path;

use auth::generate_keypair;

use crate::{flag, option};

pub fn run(backend_dir: &Path, options: &[String]) -> anyhow::Result<()> {
    let kid = option(options, "--kid")?.unwrap_or("k1");
    anyhow::ensure!(
        !kid.is_empty() && !kid.contains(['=', ',']),
        "--kid must be non-empty and contain neither `=` nor `,`"
    );
    let path = backend_dir.join(".env");
    anyhow::ensure!(
        !path.exists() || flag(options, "--force"),
        "{} already exists; pass --force to overwrite it",
        path.display()
    );

    let pair = generate_keypair();
    // Newlines are escaped so every value fits on one line; the services
    // turn `\n` back into newlines when reading the keys.
    let escape = |pem: &str| pem.trim_end().replace('\n', "\\n");
    let contents = format!(
        "# Generated by `cargo xtask gen-keys`. Never commit this file.\n\
         # The gateway signs with the private key; nano services only get public keys.\n\
         JWT_KEY_ID={kid}\n\
         JWT_PRIVATE_KEY={private}\n\
         JWT_PUBLIC_KEYS={kid}={public}\n",
        private = escape(&pair.private_pem),
        public = escape(&pair.public_pem),
    );
    std::fs::write(&path, contents)?;
    println!("wrote {} (key id `{kid}`)", path.display());
    Ok(())
}
